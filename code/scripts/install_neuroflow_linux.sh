#!/usr/bin/env bash
set -Eeuo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)"
WHEELHOUSE=""
VENV=""

usage() {
  cat <<'EOF'
Usage: install_neuroflow_linux.sh [--wheelhouse DIR] [--venv ABSOLUTE_PATH]

Install the NeuroFlow controller for the current Linux user without sudo.
Requires Linux x86_64, CPython 3.11, and a verified NeuroFlow wheelhouse.
If the project contains one dist/hpc-wheelhouses/neuroflow-* directory, it is
selected automatically. By default, installs into ~/.venvs/neuroflow-<version>;
existing versions are retained so launchers can be upgraded or rolled back.
Scientific tools and Apptainer images remain separate site dependencies.
EOF
}

while (($#)); do
  case "$1" in
    -h|--help) usage; exit 0 ;;
    --wheelhouse)
      (($# >= 2)) || { echo "Missing value for --wheelhouse" >&2; exit 2; }
      WHEELHOUSE="$2"
      shift 2
      ;;
    --venv)
      (($# >= 2)) || { echo "Missing value for --venv" >&2; exit 2; }
      VENV="$2"
      shift 2
      ;;
    *) echo "Unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
done

if [[ "$(uname -s)" != Linux || "$(uname -m)" != x86_64 ]]; then
  echo "This installer currently supports Linux x86_64 only." >&2
  exit 2
fi
PYTHON="${NEUROFLOW_PYTHON:-}"
if [[ -n "$PYTHON" ]] && ! command -v "$PYTHON" >/dev/null 2>&1; then
  echo "Configured NeuroFlow Python is unavailable: $PYTHON" >&2
  exit 2
fi
if [[ -z "$PYTHON" ]]; then
  for candidate in python3.11 python3; do
    if command -v "$candidate" >/dev/null 2>&1; then
      candidate_path="$(command -v "$candidate")"
      if "$candidate_path" -c 'import sys; raise SystemExit(0 if sys.version_info[:2] == (3, 11) else 1)' 2>/dev/null; then
        PYTHON="$candidate_path"
        break
      fi
    fi
  done
fi
[[ -n "$PYTHON" ]] || {
  echo "CPython 3.11 was not found. Make python3.11 or a Python 3.11 python3 available on PATH." >&2
  exit 2
}
shopt -s nullglob
if [[ -z "$WHEELHOUSE" ]]; then
  candidates=("$ROOT"/dist/hpc-wheelhouses/neuroflow-*)
  [[ ${#candidates[@]} -eq 1 ]] || {
    echo "Expected one bundled wheelhouse under $ROOT/dist/hpc-wheelhouses; found ${#candidates[@]}" >&2
    echo "Pass --wheelhouse DIR to select a downloaded wheelhouse explicitly." >&2
    exit 2
  }
  WHEELHOUSE="${candidates[0]}"
fi
[[ -d "$WHEELHOUSE" ]] || {
  echo "Wheelhouse not found: $WHEELHOUSE" >&2
  echo "Pass --wheelhouse DIR; the wheelhouse must contain NeuroFlow and SHA256SUMS." >&2
  exit 2
}

wheels=("$WHEELHOUSE"/neuroflow-*.whl)
[[ ${#wheels[@]} -eq 1 ]] || {
  echo "Expected one NeuroFlow wheel in $WHEELHOUSE; found ${#wheels[@]}" >&2
  exit 2
}
if command -v sha256sum >/dev/null 2>&1; then
  (cd "$WHEELHOUSE" && sha256sum -c SHA256SUMS)
elif command -v shasum >/dev/null 2>&1; then
  (cd "$WHEELHOUSE" && shasum -a 256 -c SHA256SUMS)
else
  echo "Install sha256sum or shasum to verify wheel checksums" >&2
  exit 2
fi
version="$("$PYTHON" - "${wheels[0]}" <<'PY'
from email.parser import Parser
from zipfile import ZipFile
import sys

with ZipFile(sys.argv[1]) as archive:
    metadata = next(name for name in archive.namelist() if name.endswith(".dist-info/METADATA"))
    message = Parser().parsestr(archive.read(metadata).decode("utf-8"))
if message.get("Name", "").lower() != "neuroflow":
    raise SystemExit("Wheelhouse package is not NeuroFlow")
print(message["Version"])
PY
)"
VENV="${VENV:-$HOME/.venvs/neuroflow-$version}"
[[ "$VENV" = /* ]] || { echo "The virtual environment path must be absolute: $VENV" >&2; exit 2; }

LAUNCHER_DIR="${XDG_BIN_HOME:-$HOME/.local/bin}"
[[ "$LAUNCHER_DIR" = /* ]] || { echo "XDG_BIN_HOME must be an absolute path: $LAUNCHER_DIR" >&2; exit 2; }
launchers=(neuroflow neuroflow-ui)
if "$PYTHON" -c 'import tkinter' >/dev/null 2>&1; then
  launchers+=(neuroflow-dicom-sorter)
fi
for name in "${launchers[@]}"; do
  target="$LAUNCHER_DIR/$name"
  if [[ -e "$target" && ! -L "$target" ]] && ! grep -q 'Generated by NeuroFlow Linux installer' "$target"; then
    echo "Refusing to replace an existing command: $target" >&2
    exit 2
  fi
  if [[ -L "$target" ]] && [[ "$(readlink "$target")" != "$VENV/bin/$name" ]]; then
    echo "Refusing to replace an existing symlink: $target" >&2
    exit 2
  fi
done

if [[ -e "$VENV" ]]; then
  installed_version="$("$VENV/bin/python" -c 'from importlib.metadata import version; print(version("neuroflow"))' 2>/dev/null)" || {
    echo "Existing environment is not a usable NeuroFlow install: $VENV" >&2
    exit 2
  }
  [[ "$installed_version" == "$version" ]] || {
    echo "Environment $VENV contains NeuroFlow $installed_version, expected $version." >&2
    echo "Choose another path with --venv to upgrade without replacing the existing environment." >&2
    exit 2
  }
  echo "NeuroFlow $version is already installed in $VENV; keeping that environment."
else
bash "$ROOT/code/scripts/install_neuroflow_hpc.sh" "$WHEELHOUSE" pipeline "$VENV"
fi
site_profile="${XDG_CONFIG_HOME:-$HOME/.config}/neuroflow/site.json"
legacy_site="$HOME/.config/prisma-workbench/site.json"
if [[ ! -e "$site_profile" && -e "$legacy_site" ]]; then
  site_profile="$legacy_site"
fi
if [[ ! -f "$site_profile" ]]; then
  "$VENV/bin/neuroflow" --site "$site_profile" init-site
elif "$VENV/bin/neuroflow" refresh-site --help >/dev/null 2>&1; then
  "$VENV/bin/neuroflow" --site "$site_profile" refresh-site
else
  echo "Kept existing site profile; this NeuroFlow version does not support refresh-site."
fi
mkdir -p "$LAUNCHER_DIR"

write_launcher() {
  local name="$1" command="$2" target temp argument
  shift 2
  target="$LAUNCHER_DIR/$name"
  temp="$(mktemp "$LAUNCHER_DIR/.${name}.XXXXXX")"
  {
    printf '%s\n' '#!/usr/bin/env bash' '# Generated by NeuroFlow Linux installer'
    printf 'exec %q' "$command"
    for argument in "$@"; do
      printf ' %q' "$argument"
    done
    printf ' "$@"\n'
  } > "$temp"
  chmod 755 "$temp"
  mv -f "$temp" "$target"
}

write_launcher neuroflow "$VENV/bin/neuroflow"
write_launcher neuroflow-ui "$VENV/bin/neuroflow" serve
if "$VENV/bin/python" -c 'import tkinter' >/dev/null 2>&1; then
  write_launcher neuroflow-dicom-sorter "$VENV/bin/neuroflow-dicom-sorter"
  echo "DICOM desktop sorter launcher installed."
else
  echo "Tkinter is unavailable in this Python; use the browser sorter or install Python Tk support."
fi

echo "NeuroFlow $version is ready for this user in $VENV"
echo "Commands: $LAUNCHER_DIR/neuroflow, $LAUNCHER_DIR/neuroflow-ui"
echo "Start the browser interface with: $LAUNCHER_DIR/neuroflow-ui"
if [[ ":$PATH:" != *":$LAUNCHER_DIR:"* ]]; then
  echo "To use short command names, add this to your shell profile:"
  printf '  export PATH=%q:"$PATH"\n' "$LAUNCHER_DIR"
fi
echo "On HPC, keep it bound to localhost and connect using an SSH tunnel."
echo "Site profile: $site_profile"
echo "Configure external tools and image paths there; this installer does not install them."
if "$VENV/bin/neuroflow" doctor --help >/dev/null 2>&1; then
  echo "After configuration, check pipeline readiness with: $LAUNCHER_DIR/neuroflow doctor --workflow all"
else
  echo "This NeuroFlow version has no doctor command; use the GUI job preview to validate a selected workflow."
fi
