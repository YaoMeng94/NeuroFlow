#!/usr/bin/env bash
set -Eeuo pipefail

usage() {
  cat <<'EOF'
Usage: install_neuroflow_hpc.sh WHEELHOUSE [runtime|pipeline|test] [VENV_PATH]

Install NeuroFlow offline for Linux x86_64 / CPython 3.11. The wheelhouse
must contain a SHA256SUMS file generated by build_hpc_wheelhouse.sh.
Defaults: runtime/pipeline -> ~/.venvs/neuroflow; test -> ~/.venvs/neuroflow-test.
EOF
}

if [[ $# -eq 1 && ( "$1" == "-h" || "$1" == "--help" ) ]]; then
  usage
  exit 0
fi
if [[ $# -lt 1 || $# -gt 3 ]]; then
  usage >&2
  exit 2
fi

wheelhouse="$(cd "$1" 2>/dev/null && pwd -P)" || {
  echo "Wheelhouse directory not found: $1" >&2
  exit 2
}
profile="${2:-runtime}"
case "$profile" in
  runtime) extras=""; default_env="$HOME/.venvs/neuroflow" ;;
  pipeline) extras="[pipeline]"; default_env="$HOME/.venvs/neuroflow" ;;
  test) extras="[test]"; default_env="$HOME/.venvs/neuroflow-test" ;;
  *) echo "Profile must be runtime, pipeline, or test" >&2; exit 2 ;;
esac
venv="${3:-$default_env}"
[[ "$venv" = /* ]] || { echo "VENV_PATH must be absolute: $venv" >&2; exit 2; }
[[ ! -e "$venv" ]] || { echo "Refusing to replace existing environment: $venv" >&2; exit 2; }

shopt -s nullglob
wheels=("$wheelhouse"/neuroflow-*.whl)
[[ ${#wheels[@]} -eq 1 ]] || {
  echo "Expected exactly one NeuroFlow wheel in $wheelhouse; found ${#wheels[@]}" >&2
  exit 2
}
[[ -f "$wheelhouse/SHA256SUMS" ]] || {
  echo "SHA256SUMS is missing from $wheelhouse" >&2
  exit 2
}
if command -v sha256sum >/dev/null 2>&1; then
  (cd "$wheelhouse" && sha256sum -c SHA256SUMS)
elif command -v shasum >/dev/null 2>&1; then
  (cd "$wheelhouse" && shasum -a 256 -c SHA256SUMS)
else
  echo "Install sha256sum or shasum to verify wheel checksums" >&2
  exit 2
fi

PYTHON="${NEUROFLOW_PYTHON:-}"
if [[ -n "$PYTHON" ]] && ! command -v "$PYTHON" >/dev/null 2>&1; then
  echo "Configured NeuroFlow Python is unavailable: $PYTHON" >&2
  exit 2
fi
if [[ -z "$PYTHON" ]]; then
  for candidate in python3.11 python3; do
    if command -v "$candidate" >/dev/null 2>&1; then
      candidate_path="$(command -v "$candidate")"
      if "$candidate_path" -c 'import sys; raise SystemExit(0 if sys.version_info[:2] == (3, 11) else 1)' 2>/dev/null; then
        PYTHON="$candidate_path"
        break
      fi
    fi
  done
fi
[[ -n "$PYTHON" ]] || {
  echo "CPython 3.11 was not found. Make python3.11 or a Python 3.11 python3 available on PATH." >&2
  exit 2
}
"$PYTHON" - <<'PY'
import platform
import sys

if sys.version_info[:2] != (3, 11) or platform.system() != "Linux" or platform.machine() != "x86_64":
    raise SystemExit("This wheelhouse requires Linux x86_64 and CPython 3.11")
PY

version="$("$PYTHON" - "${wheels[0]}" <<'PY'
from email.parser import Parser
from zipfile import ZipFile
import sys

with ZipFile(sys.argv[1]) as archive:
    metadata = next(name for name in archive.namelist() if name.endswith(".dist-info/METADATA"))
    message = Parser().parsestr(archive.read(metadata).decode("utf-8"))
if message.get("Name", "").lower() != "neuroflow":
    raise SystemExit("Wheelhouse package is not NeuroFlow")
print(message["Version"])
PY
)"

mkdir -p "$(dirname "$venv")"
venv_owned=0
venv_committed=0
cleanup_incomplete_venv() {
  local status=$?
  if (( status != 0 && venv_owned == 1 && venv_committed == 0 )); then
    rm -rf -- "$venv"
    echo "Removed incomplete NeuroFlow environment after installation failure: $venv" >&2
  fi
}
trap cleanup_incomplete_venv EXIT
mkdir "$venv"
venv_owned=1
"$PYTHON" -m venv "$venv"
requirement="neuroflow${extras}==${version}"
"$venv/bin/pip" install --no-index --find-links "$wheelhouse" "$requirement"
"$venv/bin/neuroflow" --help >/dev/null
venv_committed=1

site_profile="${XDG_CONFIG_HOME:-$HOME/.config}/neuroflow/site.json"
legacy_site="$HOME/.config/prisma-workbench/site.json"
if [[ ! -e "$site_profile" && -e "$legacy_site" ]]; then
  site_profile="$legacy_site"
fi
if [[ ! -e "$site_profile" ]]; then
  "$venv/bin/neuroflow" --site "$site_profile" init-site
else
  echo "Kept existing site profile: $site_profile"
fi

echo "Installed NeuroFlow $version ($profile) in $venv"
echo "Configure host tools and container images in $site_profile"
