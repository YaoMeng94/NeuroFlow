#!/usr/bin/env bash
set -Eeuo pipefail

VENV=""
LAUNCHER_DIR="${XDG_BIN_HOME:-$HOME/.local/bin}"
ASSUME_YES=0

usage() {
  cat <<'EOF'
Usage: uninstall_neuroflow_linux.sh --venv ABSOLUTE_PATH [--launcher-dir ABSOLUTE_PATH] [--yes]

Remove one NeuroFlow virtual environment installed under ~/.venvs and only
the NeuroFlow launchers that point to it. Site configuration and job data
are always preserved.
EOF
}

while (($#)); do
  case "$1" in
    -h|--help) usage; exit 0 ;;
    --venv)
      (($# >= 2)) || { echo "Missing value for --venv" >&2; exit 2; }
      VENV="$2"
      shift 2
      ;;
    --launcher-dir)
      (($# >= 2)) || { echo "Missing value for --launcher-dir" >&2; exit 2; }
      LAUNCHER_DIR="$2"
      shift 2
      ;;
    --yes) ASSUME_YES=1; shift ;;
    *) echo "Unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
done

[[ "$VENV" = /* ]] || { echo "Pass the absolute virtual environment path with --venv" >&2; exit 2; }
[[ "$LAUNCHER_DIR" = /* ]] || { echo "Launcher directory must be absolute: $LAUNCHER_DIR" >&2; exit 2; }
[[ -d "$VENV" && ! -L "$VENV" ]] || { echo "NeuroFlow environment not found or is a symlink: $VENV" >&2; exit 2; }

home_real="$(cd "$HOME" && pwd -P)"
venv_parent="$(cd "$(dirname "$VENV")" && pwd -P)"
venv_name="$(basename "$VENV")"
[[ "$venv_parent" == "$home_real/.venvs" ]] || {
  echo "Refusing to remove an environment outside $home_real/.venvs" >&2
  exit 2
}
[[ "$venv_name" == neuroflow || "$venv_name" == neuroflow-* ]] || {
  echo "Refusing to remove a path not named neuroflow or neuroflow-<version>: $VENV" >&2
  exit 2
}
[[ -x "$VENV/bin/python" ]] || { echo "Not a NeuroFlow virtual environment: $VENV" >&2; exit 2; }
version="$("$VENV/bin/python" -c 'from importlib.metadata import version; print(version("neuroflow"))' 2>/dev/null)" || {
  echo "NeuroFlow is not installed in: $VENV" >&2
  exit 2
}

if (( ! ASSUME_YES )); then
  [[ -t 0 ]] || { echo "Use --yes for non-interactive uninstall." >&2; exit 2; }
  printf 'Remove NeuroFlow %s from %s? User configuration and job data will be kept (y/N) ' "$version" "$VENV"
  read -r answer
  [[ "$answer" == y || "$answer" == Y ]] || { echo "Cancelled."; exit 0; }
fi

remove_owned_launcher() {
  local name="$1" executable="$2" target="$LAUNCHER_DIR/$1"
  [[ -f "$target" && ! -L "$target" ]] || return 0
  grep -q 'Generated by NeuroFlow Linux installer' "$target" || return 0
  grep -Fq -- "$VENV/bin/$executable" "$target" || return 0
  rm -- "$target"
}

remove_owned_launcher neuroflow neuroflow
remove_owned_launcher neuroflow-ui neuroflow
remove_owned_launcher neuroflow-dicom-sorter neuroflow-dicom-sorter
rm -rf -- "$VENV"
echo "Removed NeuroFlow $version. Site configuration and job data were preserved."
