#!/usr/bin/env bash
set -Eeuo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)"
WHEELHOUSE="${1:?Usage: test_install_neuroflow_linux.sh WHEELHOUSE}"
test_root="$(mktemp -d "${TMPDIR:-/tmp}/neuroflow-linux-install-test.XXXXXX")"
trap 'rm -rf "$test_root"' EXIT

HOME="$test_root/home" bash "$ROOT/code/scripts/install_neuroflow_linux.sh" \
  --wheelhouse "$WHEELHOUSE" \
  --venv "$test_root/home/.venvs/neuroflow"

export HOME="$test_root/home"
"$test_root/home/.venvs/neuroflow/bin/python" - <<'PY'
import json
from pathlib import Path

profile = Path.home() / ".config/neuroflow/site.json"
data = json.loads(profile.read_text())
data["qc_python"] = "/preserve-this-setting"
profile.write_text(json.dumps(data))
PY
HOME="$test_root/home" bash "$ROOT/code/scripts/install_neuroflow_linux.sh" \
  --wheelhouse "$WHEELHOUSE" \
  --venv "$test_root/home/.venvs/neuroflow"

export PATH="$HOME/.local/bin:$PATH"
neuroflow --help >/dev/null
neuroflow-ui --help >/dev/null
if neuroflow doctor --help >/dev/null 2>&1; then
  if neuroflow doctor --workflow dwi > "$test_root/doctor.log" 2>&1; then
    echo "Expected the unconfigured test profile to fail the DWI readiness check." >&2
    exit 1
  fi
  grep -Fq 'Set qsiprep_image in the site profile' "$test_root/doctor.log"
else
  echo "Skipping doctor checks: this NeuroFlow wheel predates the doctor command."
fi
neuroflow-dicom-sorter --self-test
test -f "$HOME/.config/neuroflow/site.json"
"$test_root/home/.venvs/neuroflow/bin/python" - <<'PY'
import json
from pathlib import Path

profile = Path.home() / ".config/neuroflow/site.json"
assert json.loads(profile.read_text())["qc_python"] == "/preserve-this-setting"
PY
if "$test_root/home/.venvs/neuroflow/bin/python" -c 'import tkinter' >/dev/null 2>&1; then
  test -x "$HOME/.local/bin/neuroflow-dicom-sorter"
else
  test ! -e "$HOME/.local/bin/neuroflow-dicom-sorter"
fi
grep -q 'Generated by NeuroFlow Linux installer' "$HOME/.local/bin/neuroflow-ui"

legacy_home="$test_root/legacy-home"
legacy_profile="$legacy_home/.config/prisma-workbench/site.json"
mkdir -p "$(dirname "$legacy_profile")"
printf '{"pipeline_root":"%s/.venvs/neuroflow-0.4.11/lib/python3.11/site-packages/neuroflow/pipelines","preserve_marker":"legacy"}\n' "$legacy_home" > "$legacy_profile"
HOME="$legacy_home" bash "$ROOT/code/scripts/install_neuroflow_linux.sh" \
  --wheelhouse "$WHEELHOUSE" \
  --venv "$legacy_home/.venvs/neuroflow"
"$legacy_home/.venvs/neuroflow/bin/python" - "$legacy_profile" "$legacy_home/.venvs/neuroflow" <<'PY'
import json
import sys
from pathlib import Path

profile = json.loads(Path(sys.argv[1]).read_text())
root = Path(profile["pipeline_root"]).resolve()
assert profile["preserve_marker"] == "legacy"
assert Path(sys.argv[2]).resolve() in root.parents
assert root.name == "pipelines"
PY
test ! -e "$legacy_home/.config/neuroflow/site.json"

mkdir -p "$HOME/.local/state/neuroflow/jobs"
printf 'keep\n' > "$HOME/.local/state/neuroflow/jobs/deployment-test-marker"
bash "$ROOT/code/scripts/uninstall_neuroflow_linux.sh" \
  --venv "$test_root/home/.venvs/neuroflow" \
  --launcher-dir "$HOME/.local/bin" --yes
test ! -e "$test_root/home/.venvs/neuroflow"
test ! -e "$HOME/.local/bin/neuroflow"
test ! -e "$HOME/.local/bin/neuroflow-ui"
test ! -e "$HOME/.local/bin/neuroflow-dicom-sorter"
test -f "$HOME/.config/neuroflow/site.json"
test -f "$HOME/.local/state/neuroflow/jobs/deployment-test-marker"
echo "Linux per-user installer smoke test: PASS"
